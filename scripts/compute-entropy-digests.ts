console.log('Chi-Square Statistic χ²  :', csprngSample.chiSquare.chiSquareStat.toFixed(2));
console.log('Chi-Square p-value       :', csprngSample.chiSquare.pValue.toFixed(6));
console.log('NIST SP 800-22 Verdict   :', csprngSample.chiSquare.verdictMessage);
console.log('Bit Raster Samples       :', csprngSample.bitRaster.slice(0, 32).join(''), '...(first 32 bits)');

