console.log('=== CRYPTOSCOPE ENTROPY & CSPRNG TOOLS AUDIT ===\n');

// ---------------------------------------------------------------------------
// 1. DETERMINISTIC ZERO ENTROPY TEST
// ---------------------------------------------------------------------------
console.log('--- 1. Deterministic Zero Entropy Test (1024x 0x00) ---');
const zeroStream = new Uint8Array(1024).fill(0x00);
const zeroShannon = computeShannonEntropy(zeroStream);
const zeroChi = computeChiSquareTest(zeroStream);

console.log('Shannon Entropy H        :', zeroShannon.shannonEntropy.toFixed(4), '/ 8.0000 bits/byte');
console.log('Unique Byte Symbols      :', zeroShannon.uniqueBytes, '/ 256');
console.log('Compression Potential    :', zeroShannon.theoreticalCompressionRatio, '%');
console.log('Chi-Square Statistic χ²  :', zeroChi.chiSquareStat);
console.log('Degrees of Freedom ν     :', zeroChi.degreesOfFreedom);
console.log('Chi-Square p-value       :', zeroChi.pValue.toFixed(6));
console.log('NIST SP 800-22 Verdict   :', zeroChi.verdictMessage);
console.log('Zero Entropy Test Match  :', zeroShannon.shannonEntropy === 0.0 && zeroChi.verdict === 'non-uniform' ? 'PASS (100%)' : 'FAIL');

// ---------------------------------------------------------------------------
// 2. DETERMINISTIC UNIFORM PERMUTATION TEST (4x 0..255, N=1024)
// ---------------------------------------------------------------------------
console.log('\n--- 2. Deterministic Uniform Permutation Test (4x 0..255, N=1024) ---');
const uniformBytes = new Uint8Array(1024);
for (let c = 0; c < 4; c++) {
  for (let b = 0; b < 256; b++) {
    uniformBytes[c * 256 + b] = b;
  }
}
const uniformShannon = computeShannonEntropy(uniformBytes);
const uniformChi = computeChiSquareTest(uniformBytes);

console.log('Shannon Entropy H        :', uniformShannon.shannonEntropy.toFixed(4), '/ 8.0000 bits/byte (Maximal)');
console.log('Unique Byte Symbols      :', uniformShannon.uniqueBytes, '/ 256');
console.log('Chi-Square Statistic χ²  :', uniformChi.chiSquareStat, '(Expected 0.0)');
console.log('Chi-Square p-value       :', uniformChi.pValue.toFixed(6), '(Expected 1.0)');
console.log('NIST SP 800-22 Verdict   :', uniformChi.verdictMessage);
console.log('Uniform Permutation Match:', uniformShannon.shannonEntropy === 8.0 && uniformChi.verdict === 'too-flat' ? 'PASS (100%)' : 'FAIL');

// ---------------------------------------------------------------------------
// 3. CSPRNG LIVE GENERATION (256 & 1024 BYTES)
